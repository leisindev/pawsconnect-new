"""Regenerates the 'Final prompts' half of prompts.md from prompts.py. Run: python make_prompts_md.py"""
from pathlib import Path
import prompts as P

FINAL = [("Part B - Photo-to-Profile (vision)", "PROFILE_PROMPT"),
         ("Part C1 - Inquiry triage (few-shot)", "TRIAGE_PROMPT"),
         ("Part C2 - Counselor persona 'Juniper' (system prompt)", "PERSONA_PROMPT"),
         ("Part C2 - Weakened persona (test only, used to induce a judge catch)", "WEAK_PERSONA_PROMPT"),
         ("Part C2 - LLM-as-judge guardrail", "JUDGE_PROMPT"),
         ("Part C2 - Revision instruction sent after a 'revise' verdict", "REVISION_INSTRUCTION"),
         ("Part C3 - Match explainer (chain-of-thought, sampled 3x at T=0.9)", "MATCH_PROMPT"),
         ("Part D - Post-Adoption Check-in Radar", "CHECKIN_PROMPT")]

log = Path("prompts_iterations.md").read_text(encoding="utf-8")
out = ["# PawsConnect prompts\n", "Model: gpt-4o-mini via the OpenAI Chat Completions API, JSON mode on for every structured output.\n",
       "Source of truth is `prompts.py`; this file is regenerated by `python make_prompts_md.py`.\n",
       "\n---\n\n# Part 1 - Iteration log\n", log, "\n---\n\n# Part 2 - Final prompts\n"]
for title, name in FINAL:
    out += [f"\n## {title}\n`prompts.{name}`\n\n```text\n{getattr(P, name).strip()}\n```\n"]
Path("prompts.md").write_text("\n".join(out), encoding="utf-8")
print("prompts.md written")
